#!/usr/bin/env python3
"""Export the Padilha tokens for the offline browser preview.

The preview must work from a local static server without a build step, so the
token data is embedded in a generated JavaScript file. ``--check`` keeps the
committed file in sync with ``tokens.json`` and the Python fallback.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

from design.padilha_palette import (  # noqa: E402
    CONTRAST_PAIRS,
    FALLBACK_THEMES,
    TOKENS_PATH,
    load_palette,
)

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "preview" / "palette-data.js"


def preview_payload() -> dict:
    palette = load_palette(TOKENS_PATH)
    raw = json.loads(TOKENS_PATH.read_text(encoding="utf-8"))
    return {
        "name": raw.get("name", "Padilha"),
        "version": raw.get("version", "1.1.0"),
        "updated": raw.get("updated", "2026-11-08"),
        "themes": palette["themes"],
        "fallbackThemes": FALLBACK_THEMES,
        "contrastPairs": [
            {
                "name": name,
                "foreground": foreground,
                "background": background,
                "min": minimum,
            }
            for name, foreground, background, minimum in CONTRAST_PAIRS
        ],
        "dynamicColor": raw.get("dynamicColor", {}),
        "typography": raw.get("typography", {}),
        "shape": raw.get("shape", {}),
    }


def render(payload: dict | None = None) -> str:
    data = payload if payload is not None else preview_payload()
    return (
        "/* Generated by tools/export_preview_tokens.py from docs/branding/tokens.json.\n"
        " * Do not edit by hand. Run `python3 tools/export_preview_tokens.py`.\n"
        " */\n"
        "window.PADILHA_DATA = "
        + json.dumps(data, indent=2, sort_keys=True)
        + ";\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    expected = render()
    if args.check:
        actual = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if actual != expected:
            print(f"FAIL stale preview token data: {TARGET.relative_to(ROOT)}")
            return 1
        print(f"ok {TARGET.relative_to(ROOT)}")
        return 0

    TARGET.write_text(expected, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
